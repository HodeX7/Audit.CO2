"""Recompute the fictional P2 seed baseline in an isolated temporary ledger.

Run ``python -m scripts.generate_expected`` to print the expected markdown, or
``python -m scripts.generate_expected --check`` to verify the checked-in file.
The script does not open the production database, call a model, or write the repo.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from shutil import copytree
from tempfile import TemporaryDirectory

from carbon_room import collect
from carbon_room.actors import CALCULATOR
from carbon_room.calc import factors
from carbon_room.calc import run as calc_run
from carbon_room.checks import resolve
from carbon_room.checks import run as check_run
from carbon_room.ledger import connect, init_db, ledger
from carbon_room.ledger.audit import verify_audit
from carbon_room.models import Actor
from carbon_room.report import reporter

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = ROOT / "data/seed/EXPECTED.md"


def _source_line(tag) -> str:
    label = "market, not in total" if "as reported by vendor" in tag.recompute else tag.file_name
    return f"| {tag.activity} ({label}) | {tag.kgco2e} |"


def generate() -> str:
    previous_dir = Path.cwd()
    with TemporaryDirectory(prefix="carbon-room-expected-") as temporary:
        working = Path(temporary)
        copytree(ROOT / "data/seed", working / "data/seed")
        copytree(ROOT / "data/demo_uploads", working / "data/demo_uploads")
        os.chdir(working)
        try:
            with connect(working / "expected.db") as conn:
                init_db(conn)
                factors.load(conn)
                conn.commit()
                close_id = ledger.create_close(
                    conn,
                    "2026-10",
                    ["hq", "warehouse-2", "dc-eu-west"],
                    "FS-2026-10",
                    CALCULATOR,
                    "expected-start",
                )
                conn.commit()
                ingestion = collect.ingest(conn, close_id, CALCULATOR)
                calc_run.calculate(conn, close_id)
                check_run.check(conn, close_id)
                opened = ledger.get_gaps(conn, close_id, status="OPEN")
                lead = Actor("human", "lead", "Lead", "lead")

                def gap(rule):
                    return next(item for item in ledger.get_gaps(conn, close_id, status="OPEN") if item.rule == rule)

                choice = gap("R2").options[0]
                resolve.apply(conn, gap("R2").gap_id, "pick", lead, "expected-pick", choice.params)
                option = next(item for item in gap("R3").options if item.action == "approve")
                resolve.apply(conn, gap("R3").gap_id, "approve", lead, "expected-stale", option.params)
                resolve.apply(conn, gap("R5").gap_id, "approve", lead, "expected-variance", {})
                conn.commit()
                resolve.apply(
                    conn,
                    gap("R4").gap_id,
                    "upload",
                    Actor("human", "priya", "Priya", "site_manager"),
                    "expected-upload",
                    {"path": str(working / "data/demo_uploads/warehouse2_electricity_2026-10_actual.pdf")},
                )
                report = reporter.draft(conn, close_id)
                audit = verify_audit(conn, close_id)
                source_lines = [_source_line(tag) for tag in report.s_tags]
                rules = ", ".join(sorted(gap.rule for gap in opened))
                return "\n".join(
                    (
                        "# P2 synthetic seed expected results",
                        "",
                        "Generated by `python -m scripts.generate_expected` from a temporary SQLite ledger "
                        "and fictional seed evidence.",
                        "No network, model call, or production database is used.",
                        "",
                        f"- Collector: {ingestion.statement} {len(ingestion.claims_created)} claims "
                        f"from {ingestion.sources_seen} files.",
                        f"- Initial actionable gaps: {rules} ({len(opened)} threads).",
                        "- The Warehouse R1 missing consequence is merged into its R4 period thread.",
                        "- Resolution: pick the first diesel option, apply the locked Ireland factor, "
                        "approve HQ variance, upload the held-back Warehouse bill.",
                        f"- Verified total: **{report.verified_total_tCO2e} tCO2e**.",
                        f"- Source coverage: **{report.source_coverage}**; "
                        f"emissions coverage: **{report.coverage_pct}%**.",
                        f"- Open gaps after resolution: **{len(report.gaps)}**; audit chain valid: **{audit.ok}**.",
                        "- Market-based data-centre zero is separately tagged and is not added to the location total.",
                        "",
                        "| Verified calculation / evidence | kgCO2e |",
                        "| --- | ---: |",
                        *source_lines,
                        "",
                    )
                )
        finally:
            os.chdir(previous_dir)


def main() -> int:
    result = generate()
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        if not EXPECTED.exists() or EXPECTED.read_text(encoding="utf-8") != result:
            print(f"{EXPECTED} differs from generated results", file=sys.stderr)
            return 1
        print("P2 expected results match the seed and current code")
        return 0
    if len(sys.argv) != 1:
        print("usage: python -m scripts.generate_expected [--check]", file=sys.stderr)
        return 2
    print(result, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
